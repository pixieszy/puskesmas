    public static String generateNIP(Date joinDate) {
        String nip = "";
        SimpleDateFormat sdf = new SimpleDateFormat("yyyyMMdd");
        String datePart = sdf.format(joinDate);
        
        try (Connection conn = KoneksiDatabase.getConnection()) {
            String query = "SELECT nip FROM user WHERE nip LIKE ? ORDER BY nip DESC LIMIT 1";
            try (PreparedStatement stmt = conn.prepareStatement(query)) {
                stmt.setString(1, datePart + "%");
                ResultSet rs = stmt.executeQuery();
                
                int nextNumber = 1;
                if (rs.next()) {
                    String lastNIP = rs.getString("nip");
                    int lastSequence = Integer.parseInt(lastNIP.substring(8));
                    nextNumber = lastSequence + 1;
                }
                
                String sequence = String.format("%04d", nextNumber);
                nip = datePart + sequence;
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
        
        return nip;
    }
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Date today = new Date();
        String nip = generateNIP(today);
        String nama = NamaField.getText();
        String jenis_kelamin = "";
    
    if (jenkel_laki.isSelected()) {
        jenis_kelamin = "Laki - Laki";
    } else if (jenkel_perempuan.isSelected()) {
        jenis_kelamin = "Perempuan";
    } else {
        jenis_kelamin = "";
    }
        String alamat = alamat_pegawai.getText();
        String jabatan = "none";
        String email = emailField.getText();
        String password = new String(passwordField.getPassword());
        String confirmPassword = new String(confirmPasswordField.getPassword());
        String status_akun = "deactivated";
        // Validasi input
        if (alamat.isEmpty() || jenis_kelamin.isEmpty() || nama.isEmpty() || email.isEmpty() || password.isEmpty() || confirmPassword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua field harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!password.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(this, "Password dan konfirmasi tidak cocok!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Enkripsi password
        password = EncryptDecrypt.encrypt(password);
        
        
        // Simpan ke database
        try (Connection conn = KoneksiDatabase.getConnection()) {
            String query = "INSERT INTO user (nip, nama, jenis_kelamin, alamat, jabatan, email, password, status_akun) VALUES (?, ?, ?, ?, ?, ?, ?, ?)";
            try (PreparedStatement stmt = conn.prepareStatement(query)) {
                stmt.setString(1, nip);
                stmt.setString(2, nama);
                stmt.setString(3, jenis_kelamin);
                stmt.setString(4, alamat);
                stmt.setString(5, jabatan);
                stmt.setString(6, email);
                stmt.setString(7, password);
                stmt.setString(8, status_akun);
                int rowsInserted = stmt.executeUpdate();

                if (rowsInserted > 0) {
                    JOptionPane.showMessageDialog(this, "Registrasi berhasil!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
                    dispose(); // Tutup form register
                    new LoginForm().setVisible(true); // Kembali ke login
                } else {
                    JOptionPane.showMessageDialog(this, "Registrasi gagal, coba lagi!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

