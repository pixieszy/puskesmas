    private void tpasienMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tpasienMouseClicked
        // TODO add your handling code here:
try {
    int selectedRow = tpasien.getSelectedRow();

    if (selectedRow >= 0) {
        String idpas = tpasien.getValueAt(selectedRow, 0).toString();
        String namapas = tpasien.getValueAt(selectedRow, 1).toString();
        
        // Cek form mana yang memanggil
        if (daftar != null) {
            daftar.idpas = idpas;
            daftar.pasienTerpilih();
        } else if (rekam != null) {
            rekam.idpas = idpas;
            rekam.pasienTerpilih(); // panggil metode agar form rekam langsung di-update
        } else if (resep != null) {
            resep.idpas = idpas;
            resep.namapas = namapas;
            resep.pasienTerpilih();
        }
        
        dispose();
    }
        } catch (Exception e) {
            System.out.println("Error: " + e.getMessage());
            e.printStackTrace();
            dispose();
        }
    
    }//GEN-LAST:event_tpasienMouseClicked

