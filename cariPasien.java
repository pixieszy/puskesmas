    protected void datatable() {
        String[] Baris = {"ID Pasien", "Nama Pasien"};
        tabmode = new DefaultTableModel(null, Baris);
        tpasien.setModel(tabmode);

        String sql = "SELECT id_pasien, nama_pasien FROM pasien";
        try {
            java.sql.Statement stat = conn.createStatement();
            ResultSet hasil = stat.executeQuery(sql);
            while (hasil.next()) {
                String idpas = hasil.getString("id_pasien");
                String namapas = hasil.getString("nama_pasien");

                String[] data = {idpas, namapas};
                tabmode.addRow(data);
            }
        } catch (Exception e) {
            System.out.println("Error: " + e.getMessage());
        }
    }

