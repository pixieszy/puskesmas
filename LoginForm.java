private String authenticateUser(String email, String password) {
password = EncryptDecrypt.encrypt(password);
    String nip = null;
    String nama = null;
    String statusAkun = null;
    String jenkel = null;
    String jabatan = null;

    try (Connection conn = KoneksiDatabase.getConnection()) {
        String query = "SELECT nip, nama, status_akun, jenis_kelamin,jabatan FROM user WHERE (email = ? OR nip = ?) AND password = ?";

        try (PreparedStatement stmt = conn.prepareStatement(query)) {
            stmt.setString(1, email);
            stmt.setString(2, email);
            stmt.setString(3, password);

            try (ResultSet rs = stmt.executeQuery()) {
                if (rs.next()) {
                    statusAkun = rs.getString("status_akun");

                    if ("deactivated".equalsIgnoreCase(statusAkun)) {
                        return "deactivated"; // Indikasi akun dinonaktifkan
                    }

                    nip = rs.getString("nip");
                    nama = rs.getString("nama");

                   
                    jenkel = rs.getString("jenis_kelamin");
                    jabatan = rs.getString("jabatan");
                    SessionManager.setNip(nip);
                    SessionManager.setNama(nama);
                    SessionManager.setjenkel(jenkel);
                    SessionManager.setjabatan(jabatan);
                    return "success"; // Login berhasil
                }
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }

    return "failed"; // Login gagal

}
