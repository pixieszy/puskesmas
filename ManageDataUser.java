// Fungsi untuk mengisi JTable dengan data dari database
private void loadData() {
    // Logika untuk memuat ulang data tabel dari database
    // Misalnya dengan memanggil query SELECT untuk mengambil data terbaru
    try (Connection conn = KoneksiDatabase.getConnection()) {
        String sql = "SELECT nip, nama, email, status_akun FROM user";
        Statement stmt = conn.createStatement();
        ResultSet rs = stmt.executeQuery(sql);

        // Kosongkan tabel sebelum mengisinya dengan data terbaru
        DefaultTableModel model = (DefaultTableModel) tblPegawai.getModel();
        model.setRowCount(0); // Clear existing data

        // Isi tabel dengan data terbaru
        while (rs.next()) {
            Vector<Object> row = new Vector<>();
            row.add(rs.getString("nip"));
            row.add(rs.getString("nama"));
            row.add(rs.getString("email"));
            row.add(rs.getString("status_akun"));
            row.add("Activated / Deactivated");  // Button Action
            model.addRow(row);
        }
    } catch (SQLException e) {
        e.printStackTrace();
    }
}

