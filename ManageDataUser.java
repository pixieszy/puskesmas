public class ButtonRenderer extends JButton implements TableCellRenderer {
    public ButtonRenderer() {
        setOpaque(true);
    }

    @Override
    public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
        // Dapatkan nilai status akun untuk menentukan label button
        String statusAkun = (String) table.getValueAt(row, 3);  // Kolom status_akun
        String actionButton = (statusAkun.equals("Activated")) ? "Deactivated" : "Activated";
        
        setText(actionButton);  // Set label tombol sesuai dengan status akun
        return this;
    }
}

public class ButtonEditor extends DefaultCellEditor {
    protected JButton button;
    private String label;
    private int row;

    public ButtonEditor(JCheckBox checkBox) {
        super(checkBox);
        button = new JButton();
        button.setOpaque(true);

        // Action listener untuk tombol
        button.addActionListener(new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                // Ambil data pada baris yang dipilih
                row = tblPegawai.getSelectedRow();
                String nip = (String) tblPegawai.getValueAt(row, 0);  // Kolom NIP
                String status = (String) tblPegawai.getValueAt(row, 3); // Kolom status_akun

                // Update status akun berdasarkan tombol yang diklik
                if (label.equals("Activated")) {
                    updateStatusAkun(nip, "Activated");
                } else if (label.equals("Deactivated")) {
                    updateStatusAkun(nip, "Deactivated");
                }



                button.setText(label);  // Atur label button sesuai status akun
                // After updating the status, update the button in the selected row to reflect the change
                DefaultTableModel model = (DefaultTableModel) tblPegawai.getModel();
                model.setValueAt(label, row, 4); // Update button text in Action column

                // Pindahkan fokus ke kolom NIP setelah tombol diklik
                tblPegawai.changeSelection(row, 0, false, false);  // Memindahkan fokus ke kolom NIP (kolom 0)
                
                // Trigger a refresh of the cell in the Action column
                model.fireTableCellUpdated(row, 4);  // Update kolom Action untuk menunjukkan perubahan
            }
        });
    }

    @Override
    public Component getTableCellEditorComponent(JTable table, Object value, boolean isSelected, int row, int column) {
        String statusAkun = (String) table.getValueAt(row, 3);  // Ambil status akun dari kolom ke-3 (index 3)

        // Tentukan label button berdasarkan status akun
        if (statusAkun.equals("Activated")) {
            label = "Deactivated";  // Jika status akun activated, button tampil Deactivate
        } else if (statusAkun.equals("Deactivated")) {
            label = "Activated";    // Jika status akun deactivated, button tampil Activate
        }

        button.setText(label);  // Atur label button sesuai status akun
        return button;
    }
}

