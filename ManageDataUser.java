// Fungsi untuk memperbarui status akun, lalu me-reload button di kolom Action setelah perubahan
private void updateStatusAkun(String nip, String newStatus) {
    // Menampilkan pop-up konfirmasi
    int response = JOptionPane.showConfirmDialog(
            this,
            "Apakah Anda yakin ingin mengubah status akun menjadi "+newStatus+"?",
            "Konfirmasi Perubahan Status",
            JOptionPane.YES_NO_OPTION
    );

    if (response == JOptionPane.YES_OPTION) {
        // Jika pengguna memilih YES, lanjutkan dengan update status akun
        try (Connection conn = KoneksiDatabase.getConnection()) {
            String sql = "UPDATE user SET status_akun = ? WHERE nip = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, newStatus);
            stmt.setString(2, nip);

            int rowsUpdated = stmt.executeUpdate();
            if (rowsUpdated > 0) {
                loadData();  // Memuat ulang data setelah update
                JOptionPane.showMessageDialog(this, "Berhasil memperbarui Status Akun!");
                reloadPage();
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    } else {
        // Jika pengguna memilih NO, tidak ada perubahan yang dilakukan
        JOptionPane.showMessageDialog(this, "Perubahan status dibatalkan.");
    }
}



