protected void datatable() {
    // Header kolom tabel (jumlah = 9)
    Object[] Baris = {
        "ID Daftar", "ID Pasien", "ID Dokter", "Poli", "Tanggal Kunjungan","Status Perawatan", 
        "Status"
    };

    // Buat model tabel dengan kolom yang sesuai
    tabmode = new DefaultTableModel(null, Baris);

    // Ambil keyword pencarian dari text field

    try {
        // Query SQL dengan pencarian berdasarkan ID atau nama pasien
        String sql = "select * from pendaftaran_pasien";

        Statement stat = conn.createStatement();
        ResultSet hasil = stat.executeQuery(sql);

        // Loop data dari hasil query
        while (hasil.next()) {
            tabmode.addRow(new Object[] {
                hasil.getString("id_pendaftaran"),
                hasil.getString("id_pasien"),
                hasil.getString("id_dokter"),
                hasil.getString("poli"),
                hasil.getString("tanggal_kunjungan"),
                hasil.getString("status_perawatan"),
                hasil.getString("status"),
                
            });
        }

        // Tampilkan data ke tabel
        tabeldaftar.setModel(tabmode);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Data gagal dipanggil: " + e.getMessage());
    }
}

