    private void dtnsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dtnsimpanActionPerformed
        // TODO add your handling code here:
String sql = "INSERT INTO pendaftaran_pasien (id_pendaftaran, id_pasien, id_dokter, poli, tanggal_kunjungan, status_perawatan, status) VALUES (?, ?, ?, ?, ?, ?, ?)";
try {
    PreparedStatement stat = conn.prepareStatement(sql);

    java.util.Date date = tglkunjungan.getDate();
    java.sql.Date sqlDate = null;
    if (date != null) {
        sqlDate = new java.sql.Date(date.getTime());
    }

    stat.setString(1, iddaftar.getText());
    stat.setString(2, idpasien.getText());
    stat.setString(3, iddokter.getText());
    stat.setString(4, poli.getText());

    if (sqlDate != null) {
        stat.setDate(5, sqlDate);
    } else {
        stat.setNull(5, java.sql.Types.DATE);
    }

    String cperawatanSelected = cperawatan.getSelectedItem() != null ? cperawatan.getSelectedItem().toString() : "";
    stat.setString(6, cperawatanSelected);

    String statusSelected = status.getSelectedItem() != null ? status.getSelectedItem().toString() : "";
    stat.setString(7, statusSelected);

    stat.executeUpdate();
    JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
    kosong();
    iddaftar.requestFocus();

} catch (SQLException e) {
    JOptionPane.showMessageDialog(null, "Data gagal disimpan: " + e.getMessage());
}

datatable();


    }//GEN-LAST:event_dtnsimpanActionPerformed

    private void dtnhapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dtnhapusActionPerformed
        // TODO add your handling code here:
              String idText = iddaftar.getText().trim();
    if (idText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih data yang akan dihapus terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    // Konfirmasi hapus dengan user
    int konfirmasi = JOptionPane.showConfirmDialog(
        this, 
        "Apakah Anda yakin ingin menghapus data dengan ID: " + idText + "?", 
        "Konfirmasi Hapus", 
        JOptionPane.YES_NO_OPTION,
        JOptionPane.QUESTION_MESSAGE
    );
    
    if (konfirmasi == JOptionPane.YES_OPTION) {
        try {
            // Query DELETE yang benar - pastikan nama tabel dan kolom sesuai
            String sql = "DELETE FROM pendaftaran_pasien WHERE id_pendaftaran=?";
            PreparedStatement stat = conn.prepareStatement(sql);
            
            // Set parameter dengan tipe data yang sesuai (int jika ID bertipe integer)
            stat.setInt(1, Integer.parseInt(idText));
            
            // Eksekusi query dan periksa hasilnya
            int rowsAffected = stat.executeUpdate();
            
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                
                // Clear form input
                iddaftar.setText("");
                // Clear field lain jika ada (contoh):
                // txtnama.setText("");
                // txtalamat.setText("");
                
                // Refresh tampilan data
                datatable();
                kosong();
                
            } else {
                JOptionPane.showMessageDialog(this, "Data dengan ID tersebut tidak ditemukan!", "Info", JOptionPane.INFORMATION_MESSAGE);
            }
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); 
        }
    }
    }//GEN-LAST:event_dtnhapusActionPerformed

    private void tabeldaftarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabeldaftarMouseClicked
        // TODO add your handling code here:
try {
    int bar = tabeldaftar.getSelectedRow();
    if (bar == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data terlebih dahulu dari tabel.");
        return;
    }

    iddaftar.setText(tabmode.getValueAt(bar, 0).toString());
    idpasien.setText(tabmode.getValueAt(bar, 1).toString());
    iddokter.setText(tabmode.getValueAt(bar, 2).toString());
    poli.setText(tabmode.getValueAt(bar, 3).toString());

    Object cPerawatanObj = tabmode.getValueAt(bar, 5);
    if (cPerawatanObj != null) {
        cperawatan.setSelectedItem(cPerawatanObj.toString());
    } else {
        cperawatan.setSelectedIndex(-1);
    }

    Object statusObj = tabmode.getValueAt(bar, 6);
    if (statusObj != null) {
        status.setSelectedItem(statusObj.toString());
    } else {
        status.setSelectedIndex(-1);
    }

    // Kalau tanggal di kolom 5 atau 6 belum jelas, coba cek dan sesuaikan
    // Misal tanggal di kolom 5, kita ubah menjadi:
    Object objTanggal = tabmode.getValueAt(bar, 4); // atau 6 kalau di situ
    if (objTanggal != null) {
        String tgldaftar = objTanggal.toString();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        java.util.Date tanggal = sdf.parse(tgldaftar);
        tglkunjungan.setDate(tanggal);
    } else {
        tglkunjungan.setDate(null);
    }

} catch (Exception e) {
    e.printStackTrace();
    JOptionPane.showMessageDialog(this, "Gagal menampilkan data: " + e.getMessage());
}


    }//GEN-LAST:event_tabeldaftarMouseClicked

